function main_linear_base(config_path, model_path, output_root)
%MAIN_LINEAR_BASE Run MATLAB postprocess for the linear/base model.

    arguments
        config_path (1, :) char
        model_path (1, :) char
        output_root (1, :) char
    end

    config = read_json_file(config_path);
    result = run_beam_model_pipeline(struct( ...
        "model_path", model_path, ...
        "output_root", output_root, ...
        "num_modes", 6, ...
        "mode_points", 241, ...
        "include_mic", false ...
    ));

    summary = struct();
    summary.model_line = "linear";
    summary.model_id = "base";
    summary.model_class = "Linear_Base_EB";
    summary.beam_formulation = "Euler-Bernoulli";
    summary.config_path = string(config_path);
    summary.output_root = string(output_root);
    summary.results_dir = string(fullfile(output_root, "results"));
    summary.f1_hz = get_freq_value(result.freq_table, 1);
    summary.f2_hz = get_freq_value(result.freq_table, 2);
    summary.f3_hz = get_freq_value(result.freq_table, 3);
    summary.max_tip_displacement_m = max(abs(result.tip_w));
    summary.L_total = string(config.geometry.L_total);
    summary.L_free = string(config.geometry.L_free);
    summary.b = string(config.geometry.b);
    summary.h = string(config.geometry.h);
    summary.rho = string(config.material.rho);
    summary.E = string(config.material.E);
    summary.nu = string(config.material.nu);
    summary.root = string(config.boundary.root);
    summary.tip = string(config.boundary.tip);
    summary.excitation_mode = string(config.excitation.mode);
    summary.J = string(config.excitation.J);
    summary.tau_imp = string(config.excitation.tau_imp);
    summary.pulse_shape = string(config.excitation.pulse_shape);
    summary.eigen_modes = string(config.studies.eigen_modes);
    summary.time_end = string(config.studies.time_end);
    summary.time_step = string(config.studies.time_step);

    results_dir = fullfile(output_root, "results");
    export_run_summary(results_dir, summary);
    publish_output_bundle(output_root, summary, struct( ...
        "config_path", config_path, ...
        "table_files", {{ ...
            fullfile(results_dir, "frequencies.csv"), ...
            fullfile(results_dir, "tip_timeseries.csv"), ...
            fullfile(results_dir, "mode_shapes.csv") ...
        }}, ...
        "figure_files", {{ ...
            fullfile(results_dir, "frequencies_bar.png"), ...
            fullfile(results_dir, "tip_timeseries.png"), ...
            fullfile(results_dir, "tip_fft.png"), ...
            fullfile(results_dir, "pgmode_mode01.png"), ...
            fullfile(results_dir, "pgmode_mode02.png"), ...
            fullfile(results_dir, "pgmode_mode03.png"), ...
            fullfile(results_dir, "pgmode_mode04.png"), ...
            fullfile(results_dir, "pgmode_mode05.png"), ...
            fullfile(results_dir, "pgmode_mode06.png") ...
        }}, ...
        "artifact_files", {{ ...
            fullfile(results_dir, "run_summary.json"), ...
            fullfile(results_dir, "run_summary.txt") ...
        }} ...
    ));
end

function value = get_freq_value(freq_table, idx)
    if height(freq_table) >= idx
        value = freq_table.freq_hz(idx);
    else
        value = [];
    end
end
